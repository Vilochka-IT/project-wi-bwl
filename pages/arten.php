    <h2>Klassische und moderne Verfahren</h2>
    <p>Neben Rechnung, Vorkasse, SEPA-Lastschrift, Überweisung und Kreditkarte gibt es zahlreiche E-Payment-Lösungen:</p>

    <div class="verfahren">
      <h3>PayPal</h3>
      <p>Nutzer:innen erstellen ein Konto und hinterlegen Zahlungsdaten. Beim Bezahlen wird man zu PayPal weitergeleitet und bestätigt mit Login.</p>
      <p class="vorteil">Vorteile: Sicher, schnelle Zahlung, keine erneute Eingabe der Bankdaten. Kostenlos für Privatkunden.</p>
    </div>

    <div class="verfahren">
      <h3>Klarna</h3>
      <ul>
        <li><strong>Klarna Sofort:</strong> Zahlung per Onlinebanking, sofortige Bestätigung, Geldfluss über Dienstleister.</li>
        <li><strong>Klarna Rechnung/Ratenkauf:</strong> Ware sofort, Bezahlung später oder in Raten.</li>
      </ul>
    </div>

    <div class="verfahren">
      <h3>Amazon Pay</h3>
      <p>Bezahlen mit den im Amazon-Konto gespeicherten Daten – außerhalb von Amazon. Kontodaten werden nicht übermittelt.</p>
      <p class="vorteil">Vorteil: Schnell und vertraut für Amazon-Nutzer:innen.</p>
    </div>

    <div class="verfahren">
      <h3>Apple Pay</h3>
      <p>Kontaktlose Zahlung mit Face ID, Touch ID oder Gerätecode via Apple Wallet.</p>
      <p><strong>Voraussetzung:</strong> Apple-Gerät mit NFC.</p>
      <p class="vorteil">Vorteil: Sicher & schnell – ohne physische Karte.</p>
    </div>

    <div class="verfahren">
      <h3>Google Pay</h3>
      <p>Ähnlich wie Apple Pay – für Android. Karte wird im Wallet gespeichert und für kontaktlose Zahlungen genutzt.</p>
      <p><strong>Voraussetzung:</strong> Android-Gerät mit NFC.</p>
      <p class="vorteil">Vorteil: Einfaches, schnelles Zahlen mit dem Smartphone.</p>
    </div>

    <div class="verfahren">
      <h3>Kryptowährungen</h3>
      <p>Zahlung erfolgt direkt über Wallets oder Dienstleister (z. B. BitPay).</p>
      <p class="vorteil">Vorteil: Dezentral, ohne Bank, weltweit nutzbar.</p>
      <p class="hinweis">Hinweis: Hohe Kursschwankungen. Nicht alle Händler akzeptieren Krypto.</p>
    </div>

