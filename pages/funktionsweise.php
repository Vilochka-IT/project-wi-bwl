 <p>Für E-Payments braucht man: eine Internetverbindung, ein Shopsystem oder Kassensystem mit Zahlungsschnittstelle, einen Vertrag mit einem Zahlungsdienstleister (z. B. PayPal, Stripe) und zertifizierte Sicherheitssysteme wie PCI-DSS für den sicheren Umgang mit Zahlungsdaten.</p>   
